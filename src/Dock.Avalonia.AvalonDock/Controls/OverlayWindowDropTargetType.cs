namespace AvalonDock.Controls;

/// <summary>Identifies the selector displayed by an AvalonDock overlay.</summary>
public enum OverlayWindowDropTargetType
{
    /// <summary>The outer left selector.</summary>
    DockingManagerDockLeft,
    /// <summary>The outer top selector.</summary>
    DockingManagerDockTop,
    /// <summary>The outer right selector.</summary>
    DockingManagerDockRight,
    /// <summary>The outer bottom selector.</summary>
    DockingManagerDockBottom,
    /// <summary>The document pane's left selector.</summary>
    DocumentPaneDockLeft,
    /// <summary>The document pane's top selector.</summary>
    DocumentPaneDockTop,
    /// <summary>The document pane's right selector.</summary>
    DocumentPaneDockRight,
    /// <summary>The document pane's bottom selector.</summary>
    DocumentPaneDockBottom,
    /// <summary>The document pane's center selector.</summary>
    DocumentPaneDockInside,
    /// <summary>The tool pane's left selector.</summary>
    AnchorablePaneDockLeft,
    /// <summary>The tool pane's top selector.</summary>
    AnchorablePaneDockTop,
    /// <summary>The tool pane's right selector.</summary>
    AnchorablePaneDockRight,
    /// <summary>The tool pane's bottom selector.</summary>
    AnchorablePaneDockBottom,
    /// <summary>The tool pane's center selector.</summary>
    AnchorablePaneDockInside
}
